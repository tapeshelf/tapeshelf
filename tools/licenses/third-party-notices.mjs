#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from the production dependency trees of backend/, frontend/ and
// extension/ (run `npm ci` in each first). Also fails when a production dependency carries a license outside the
// allowlist, so a copyleft library cannot slip in unnoticed.
//   node tools/licenses/third-party-notices.mjs           write the file
//   node tools/licenses/third-party-notices.mjs --check   only verify the allowlist
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ALLOWED = new Set([
  'MIT', 'MIT-0', 'ISC', '0BSD', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', 'BlueOak-1.0.0',
  'CC0-1.0', 'Unlicense', 'Python-2.0', 'OFL-1.1', 'CC-BY-4.0',
  // sharp's prebuilt libvips: dynamically loaded, see the note in the generated file
  'LGPL-3.0-or-later', 'Apache-2.0 AND LGPL-3.0-or-later',
  // Mediabunny in the browser extension: file-level copyleft, compatible with the AGPL; its files,
  // with the one line the build changes, are in the extension as readable source
  'MPL-2.0',
]);

function licenseOf(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (!l) return 'UNKNOWN';
  if (typeof l === 'string') return l.replace(/^\((.*)\)$/, '$1');
  if (Array.isArray(l)) return l.map((x) => (typeof x === 'string' ? x : x.type)).join(' OR ');
  return l.type ?? 'UNKNOWN';
}
// Reviewed one by one: shipped unmodified, never loaded by TapeShelf itself.
const EXCEPTIONS = {
  elkjs: 'EPL-2.0 (weak, file-level copyleft): part of Prisma Studio, which arrives with the Prisma CLI that the migrate container runs; never used',
};
// "A OR B": one alternative must be allowed; "A AND B": every part must be.
const allowed = (lic) =>
  lic.split(/\s+or\s+/i).some((alt) => alt.split(/\s+and\s+/i).every((part) => ALLOWED.has(part.replace(/[()]/g, '').trim())));

function productionTree(dir) {
  const out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], {
    cwd: join(root, dir), encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 << 20,
  });
  const seen = new Map();
  for (const path of out.split('\n').slice(1)) {
    if (!path.includes('node_modules')) continue;
    const pkg = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'));
    const key = `${pkg.name}@${pkg.version}`;
    if (!seen.has(key)) seen.set(key, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), url: repoUrl(pkg) });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}
function repoUrl(pkg) {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  return (r ?? pkg.homepage ?? '').replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://')
    .replace(/^github:/, 'https://github.com/');
}

const trees = {
  backend: productionTree('backend'),
  frontend: productionTree('frontend'),
  extension: productionTree('extension'),
};
const bad = Object.entries(trees).flatMap(([dir, list]) =>
  list.filter((p) => !allowed(p.license) && !EXCEPTIONS[p.name]).map((p) => `${dir}: ${p.name}@${p.version} (${p.license})`));
if (bad.length) {
  console.error(`Production dependencies with a license outside the allowlist:\n  ${bad.join('\n  ')}`);
  process.exit(1);
}
if (process.argv.includes('--check')) {
  console.log(`ok: ${trees.backend.length} backend, ${trees.frontend.length} frontend and ${trees.extension.length} extension packages, all licenses allowed`);
  process.exit(0);
}

const table = (list) => ['| Package | Version | License |', '| --- | --- | --- |',
  ...list.map((p) => `| ${p.url ? `[${p.name}](${p.url})` : p.name} | ${p.version} | ${p.license} |`)].join('\n');
const summary = (list) => Object.entries(list.reduce((m, p) => ((m[p.license] = (m[p.license] ?? 0) + 1), m), {}))
  .sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ${n}`).join(', ');

const md = `# Third-party notices

TapeShelf is licensed under the GNU Affero General Public License v3.0 (see \`LICENSE\`). It is built on the
work of others; their licenses are listed below. This file is generated by
\`node tools/licenses/third-party-notices.mjs\` — do not edit it by hand.

## Components outside npm

| Component | Where | License | Notes |
| --- | --- | --- | --- |
| [FFmpeg](https://ffmpeg.org) | worker image (Debian package \`ffmpeg\`) | GPL-2.0-or-later (built with libx264) | Run as a separate program, not linked. Source: [sources.debian.org/src/ffmpeg](https://sources.debian.org/src/ffmpeg/). H.264 encoding may be subject to patent licensing in some countries. |
| [libvips](https://www.libvips.org) | backend images, via \`sharp\`'s prebuilt binaries | LGPL-3.0-or-later | Dynamically loaded shared library; may be replaced by the user. |
| [Inter](https://rsms.me/inter/), [Unbounded](https://github.com/googlefonts/unbounded), [JetBrains Mono](https://github.com/JetBrains/JetBrainsMono) | \`backend/assets/fonts\` (contact sheets, timers and captions of the video editor) | OFL-1.1 | License texts next to the font files. |
| [Golos Text](https://github.com/googlefonts/golos-text), [Unbounded](https://github.com/googlefonts/unbounded), [JetBrains Mono](https://github.com/JetBrains/JetBrainsMono) | web app and browser extension, via \`@fontsource-variable\` | OFL-1.1 | The extension's packages carry the license texts next to the fonts. |
| [Caddy](https://caddyserver.com) | web image | Apache-2.0 | |
| [Node.js](https://nodejs.org) | api and worker images | MIT | |
| [PostgreSQL client](https://www.postgresql.org) | worker image (\`pg_dump\`, \`pg_restore\`) | PostgreSQL License | |
| [Debian](https://www.debian.org) | base of the api and worker images | various free licenses | |

## Reviewed exceptions

${Object.entries(EXCEPTIONS).map(([n, why]) => `- \`${n}\` — ${why}.`).join('\n')}

## Backend runtime dependencies (${trees.backend.length})

Summary: ${summary(trees.backend)}.

${table(trees.backend)}

## Web app dependencies bundled into the browser build (${trees.frontend.length})

Summary: ${summary(trees.frontend)}.

${table(trees.frontend)}

## Browser extension dependencies bundled into the extension (${trees.extension.length})

Summary: ${summary(trees.extension)}. The extension's build changes one line of Mediabunny's MPEG-TS
demuxer (it keeps less in memory); the change is in \`extension/build.mjs\`, and the bundled files stay
readable source, under the MPL-2.0 like the rest of Mediabunny.

${table(trees.extension)}
`;
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), md);
console.log(`THIRD_PARTY_NOTICES.md: ${trees.backend.length} backend, ${trees.frontend.length} frontend, ${trees.extension.length} extension packages`);
