/**
 * The Russian texts have the English keys. Next to a plural `x_one`/`x_other` they also give
 * `x_few`/`x_many` (Russian has four forms; without them i18next falls back to English).
 */
type PluralExtras<T> = {
  [
    K in keyof T as K extends `${infer B}_one`
      ? `${B}_few` | `${B}_many`
      : never
  ]: string;
};
type Shape<T> = {
  [K in keyof T]: T[K] extends string ? string : Shape<T[K]>;
} & PluralExtras<T>;

